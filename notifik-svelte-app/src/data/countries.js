export const getFilteredCountries = (allowedCountries = []) => {
  if (!allowedCountries?.length)
    return Object.entries(COUNTRY_DATA).map(([key, data]) => toCountry(key, data));
  return allowedCountries
    .map((k) => {
      const u = k.trim().toUpperCase();
      return toCountry(u, COUNTRY_DATA[u]);
    })
    .filter(Boolean);
};
