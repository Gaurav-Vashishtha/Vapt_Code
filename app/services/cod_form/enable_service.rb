# frozen_string_literal: true

require "json"

module CodForm
  # Mode switch of the Setup screen (D.15 `POST /cod_form/mode`, DSH-5).
  #
  #   CodForm::EnableService.call(shop)     # legacy → cod_form
  #   CodForm::EnableService.disable(shop)  # cod_form → legacy
  #
  # Turning on: creates the default form (published, C.2 defaults) and the default button config
  # (preset B) when missing, completes `general` / `fraud` with defaults, fills
  # `general.countries` with the shop's own country on the first enable (PM assumption 4), makes
  # sure a preview token exists, then syncs the storefront domains and the metafield.
  # Nothing on `Setting` is read or changed, and no health item blocks the switch.
  class EnableService
    DEFAULT_TEXTS_PATH = "config/cod_form/default_texts.json"

    # Used only while config/cod_form/default_texts.json (generated by the storefront package,
    # WS5) is missing or unreadable. PM assumptions 2 and 8.
    FALLBACK_TEXTS = {
      "en" => {
        "title" => "Cash on Delivery",
        "submit" => "Complete order — {total}",
        "pay_online" => "Pay online instead",
        "error_blocked" => "Cash on delivery is not available for this order.",
        "error_no_shipping" => "We don't deliver to this address yet.",
        "thank_you_message" => "Thank you {first_name}! Your order {order_name} is confirmed."
      }
    }.freeze

    class << self
      # => CodForm::ShopConfig (mode "cod_form")
      def call(shop)
        config = CodForm::ShopConfig.for(shop)
        first_enable = config.enabled_at.nil?

        CodForm::ShopConfig.transaction do
          CodForm::Form.default_for(shop)
          CodForm::ButtonConfig.for(shop)

          general = CodFormAdmin::Validators::General.complete(config.general, engine_default(:general))
          general["countries"] = first_countries(shop) if first_enable && general["countries"].empty?
          fraud = CodFormAdmin::Validators::Fraud.complete(config.fraud, engine_default(:fraud))

          config.preview_token = SecureRandom.hex(16) if config.preview_token.blank?
          config.update!(storefront_mode: CodForm::ShopConfig::STOREFRONT_MODE_COD_FORM,
                         general: general, fraud: fraud)
          config.bump_version!
        end

        CodForm::DomainSyncJob.perform_async(shop.id)
        config
      end

      # => CodForm::ShopConfig (mode "legacy"). Forms, buttons, rates and offers are kept.
      def disable(shop)
        config = CodForm::ShopConfig.for(shop)
        return config unless config.cod_form_mode?

        config.update!(storefront_mode: CodForm::ShopConfig::STOREFRONT_MODE_LEGACY)
        config.bump_version!
        config
      end

      # {"en" => {text_key => text}, "hi" => {...}, …} for `GET /cod_form/forms/defaults`.
      # Loaded lazily and re-read when the file changes; never raises.
      def default_texts
        path = defined?(Rails) && Rails.respond_to?(:root) && Rails.root ? Rails.root.join(DEFAULT_TEXTS_PATH).to_s : DEFAULT_TEXTS_PATH
        load_texts(path)
      end

      # Pure apart from the file read: tolerates a missing / broken file and the two shapes
      # {"en": {...}} and {"texts": {"en": {...}}}.
      def load_texts(path)
        mtime = File.exist?(path) ? File.mtime(path) : nil
        return @texts if defined?(@texts) && @texts && @texts_path == path && @texts_mtime == mtime

        @texts_path = path
        @texts_mtime = mtime
        @texts = mtime ? parse_texts(File.read(path)) : FALLBACK_TEXTS
      rescue StandardError
        @texts = FALLBACK_TEXTS
      end

      def parse_texts(json)
        data = JSON.parse(json)
        data = data["texts"] if data.is_a?(Hash) && data["texts"].is_a?(Hash)
        sets = data.is_a?(Hash) ? data.select { |_, set| set.is_a?(Hash) } : {}
        return FALLBACK_TEXTS if sets.empty?

        sets.key?("en") ? sets : FALLBACK_TEXTS.merge(sets)
      rescue JSON::ParserError
        FALLBACK_TEXTS
      end

      private

      def first_countries(shop)
        code = shop.country_code.to_s.strip.upcase
        code.match?(/\A[A-Z]{2}\z/) ? [code] : []
      end

      def engine_default(name)
        CodForm::Engine::Defaults.public_send(name)
      rescue StandardError
        nil
      end
    end
  end
end
